def _pull_unscored(since: datetime | None, limit: int) -> list[dict]:
    """Pull unscored institutional_flow posts."""
    with get_conn() as conn:
        with conn.cursor() as cur:
            if since is None:
                cur.execute(
                    """
                    SELECT rp.post_id, rp.time, rp.entity_id, rp.adapter_id,
                           rp.source_class, rp.tier, rp.text, rp.raw
                    FROM raw_posts rp
                    WHERE rp.source_class = %s
                      AND NOT EXISTS (
                          SELECT 1 FROM sentiment_scores ss
                          WHERE ss.entity_id = rp.entity_id
                            AND ss.source_class = rp.source_class
                            AND ss.time = rp.time
                      )
                    ORDER BY rp.time ASC
                    LIMIT %s;
                    """,
                    (SOURCE_CLASS, limit),
                )
            else:
                cur.execute(
                    """
                    SELECT rp.post_id, rp.time, rp.entity_id, rp.adapter_id,
                           rp.source_class, rp.tier, rp.text, rp.raw
                    FROM raw_posts rp
                    WHERE rp.source_class = %s
                      AND rp.time > %s
                      AND NOT EXISTS (
                          SELECT 1 FROM sentiment_scores ss
                          WHERE ss.entity_id = rp.entity_id
                            AND ss.source_class = rp.source_class
                            AND ss.time = rp.time
                      )
                    ORDER BY rp.time ASC
                    LIMIT %s;
                    """,
                    (SOURCE_CLASS, since, limit),
                )
            cols = [d.name for d in cur.description]
            return [dict(zip(cols, row)) for row in cur.fetchall()]


def _write_scores(rows: list[tuple]) -> int:
    """Write scored rows to sentiment_scores. Returns rows written."""
    if not rows:
        return 0
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.executemany(
                """
                INSERT INTO sentiment_scores
                    (time, entity_id, source_class, polarity, confidence, tier, post_count)
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (entity_id, source_class, time) DO NOTHING;
                """,
                rows,
            )
            written = cur.rowcount
        conn.commit()
    return written


def _get_watermark() -> datetime | None:
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT last_scored_at FROM scoring_watermark WHERE source_class = %s;",
                (SOURCE_CLASS,),
            )
            row = cur.fetchone()
    return row[0] if row else None


def _set_watermark(ts: datetime) -> None:
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                INSERT INTO scoring_watermark (source_class, last_scored_at)
                VALUES (%s, %s)
                ON CONFLICT (source_class) DO UPDATE
                    SET last_scored_at = EXCLUDED.last_scored_at,
                        updated_at = now();
                """,
                (SOURCE_CLASS, ts),
            )
        conn.commit()
